CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id VARCHAR(120) NOT NULL,
    event_type VARCHAR(120) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    retry_count INTEGER NOT NULL,
    sequence_number BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE INDEX idx_iam_outbox_status_sequence ON outbox_events (status, sequence_number);
CREATE INDEX idx_iam_outbox_aggregate ON outbox_events (aggregate_type, aggregate_id);
