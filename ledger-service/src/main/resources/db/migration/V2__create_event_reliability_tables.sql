CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    aggregate_type VARCHAR(80) NOT NULL,
    aggregate_id VARCHAR(120) NOT NULL,
    event_type VARCHAR(120) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    retry_count INTEGER NOT NULL,
    sequence_number BIGINT GENERATED BY DEFAULT AS IDENTITY
);

CREATE INDEX idx_ledger_outbox_status_sequence ON outbox_events (status, sequence_number);
CREATE INDEX idx_ledger_outbox_aggregate ON outbox_events (aggregate_type, aggregate_id);

CREATE TABLE inbox_events (
    id UUID PRIMARY KEY,
    event_id UUID NOT NULL,
    event_type VARCHAR(120) NOT NULL,
    consumer_name VARCHAR(120) NOT NULL,
    status VARCHAR(40) NOT NULL,
    result_payload TEXT,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_ledger_inbox_event_consumer UNIQUE (event_id, consumer_name)
);

CREATE INDEX idx_ledger_inbox_status_received ON inbox_events (status, received_at);
